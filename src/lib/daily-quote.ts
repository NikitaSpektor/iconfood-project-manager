export function quoteOfTheDay(base = new Date()): Quote {
  const start = Date.UTC(base.getFullYear(), 0, 0);
  const current = Date.UTC(base.getFullYear(), base.getMonth(), base.getDate());
  const dayOfYear = Math.floor((current - start) / 86400000);
  const index = (dayOfYear + base.getFullYear()) % QUOTES.length;
  return QUOTES[index];
}

export default quoteOfTheDay;
