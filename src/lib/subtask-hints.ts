const STOP = new Set([
  'и', 'в', 'на', 'по', 'для', 'из', 'с', 'к', 'о', 'об', 'от', 'до', 'за', 'при', 'что',
  'как', 'все', 'нужно', 'надо', 'новый', 'новая', 'новое', 'сделать', 'подготовить',
  'провести', 'этот', 'наш', 'нашего', 'который',
]);

function words(text: string) {
  return text
    .toLowerCase()
    .replace(/[^a-zа-яё0-9\s]/gi, ' ')
    .split(/\s+/)
    .filter((w) => w.length > 2 && !STOP.has(w))
    .map((w) => w.slice(0, 5));
}

