export function localSubtaskHints(title: string, restaurant: string): string[] {
  const clean = title.trim().replace(/\s+/g, ' ');
  const lower = clean.toLowerCase();
  const subject = clean.replace(/^./, (c) => c.toLowerCase());
  const place = restaurant && restaurant !== 'Управляющая компания' ? restaurant : '';

  let bestIntent: Intent | null = null;
  let intentScore = 0;
  for (const intent of INTENTS) {
    const score = intent.keys.filter((k) => lower.includes(k)).length;
    if (score > intentScore) {
      intentScore = score;
      bestIntent = intent;
    }
  }
  if (bestIntent) return bestIntent.steps(place);

  const keys = words(clean);
  let best: (typeof TEMPLATES)[number] | null = null;
  let bestScore = 0;
  for (const tpl of TEMPLATES) {
    const pool = words(tpl.name + ' ' + tpl.hint);
    const score = keys.filter((k) => pool.includes(k)).length;
    if (score > bestScore) {
      bestScore = score;
      best = tpl;
    }
  }
  if (best && bestScore >= 2) return [...best.steps];

  return [
    `Уточнить цель и ожидаемый результат: ${subject}`,
    'Согласовать сроки и ресурсы с руководителем',
    'Подготовить материалы и распределить работу',
    place ? `Выполнить основную часть — ${place}` : 'Выполнить основную часть работы',
    'Проверить результат и снять замечания',
    'Закрыть задачу и сообщить команде',
  ];
}
